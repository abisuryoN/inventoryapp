    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
    
        
    int baris = jTable_Kategori.getSelectedRow();

    if (baris == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Pilih data terlebih dahulu!"
        );
        return;
    }

    String id =
            jTable_Kategori.getValueAt(baris, 1).toString();

    String nama =
            jTable_Kategori.getValueAt(baris, 2).toString();

    String status =
            jTable_Kategori.getValueAt(baris, 3).toString();

    String keterangan =
            jTable_Kategori.getValueAt(baris, 4).toString();

    TambahKategori tb =
            new TambahKategori(null, true);

    tb.setDataEdit(
            id,
            nama,
            keterangan,
            status
    );

    tb.setVisible(true);

    loadDataToDatabase();
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
    
        
    int baris = jTable_Kategori.getSelectedRow();

    if (baris == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Pilih data terlebih dahulu!"
        );

        return;
    }

    int konfirmasi =
            javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Yakin ingin menghapus kategori ini?",
                    "Konfirmasi",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {

        try {

            String id =
                    jTable_Kategori.getValueAt(baris, 1).toString();

            java.sql.Connection conn =
                    koneksi.getConnection();

            String sql =
                    "DELETE FROM KategoriBarang WHERE id=?";

            java.sql.PreparedStatement ps =
                    conn.prepareStatement(sql);

            ps.setString(1, id);

            ps.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Data berhasil dihapus"
            );

            loadDataToDatabase();

        } catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage()
            );
        }
    }
    }//GEN-LAST:event_jButtonHapusActionPerformed

