   public void loadDataToDatabase() {
        // 1. Ambil model dari jTable milikmu
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable_Kategori.getModel();
        
        // 🌟 KUNCI UTAMA 1: Kosongkan baris tabel lama sebelum me-load yang baru
        model.setRowCount(0); 
        
        String sql = "SELECT * FROM KategoriBarang WHERE status IN ('Aktif','Tidak Aktif')";
        
        try (java.sql.Connection conn = koneksi.getConnection();
            java.sql.Statement st = conn.createStatement();
            java.sql.ResultSet rs = st.executeQuery(sql)) {
            
            int no = 1;
            while (rs.next()) {
                // Ambil data sesuai kolom DB kamu
                Object[] row = {
                    no++,
                    rs.getString("id"),
                    rs.getString("name"),
                    rs.getString("status"),
                    rs.getString("keterangan")
                };
                model.addRow(row); // Masukkan baris baru ke tabel
            }
            
        } catch (Exception e) {
            System.out.println("Error load data: " + e.getMessage());
        }
        
    
   jTable_Kategori.getColumn("Status").setCellRenderer(new javax.swing.table.DefaultTableCellRenderer() {
       
        public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
            java.awt.Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
            
            if (value != null) {
                String status = value.toString().trim();
                
                // Memberikan warna teks berdasarkan nilai di database
                if (status.equalsIgnoreCase("Aktif")) {
                    c.setForeground(new java.awt.Color(0, 153, 0)); // Warna Hijau
                } else if (status.equalsIgnoreCase("Tidak Aktif")) {
                    c.setForeground(java.awt.Color.RED); // Warna Merah
                } else {
                    c.setForeground(table.getForeground()); // Warna Hitam standar jika kosong
                }
            }
            
            // Mengatur background agar saat baris diklik (di-select), warna hijau/merah teksnya tetap jelas
            if (isSelected) {
                c.setBackground(table.getSelectionBackground());
            } else {
                c.setBackground(table.getBackground());
            }
            
            return c;
        }
   
    });
   } 
